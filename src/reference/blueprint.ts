function block(id: string, value: string, heading = false): SavedNode {
  return {
    type: heading ? "heading" : "paragraph",
    version: 1,
    blockId: id,
    direction: null,
    format: "",
    indent: 0,
    ...(heading ? { tag: "h2" } : { textStyle: "" }),
    children: [text(value)],
  };
}
function make(expanded: boolean): Snapshot {
  return {
    revision: expanded ? "blueprint-1" : "draft-1",
    label: expanded ? "可實作的交付藍圖" : "初步設計草案",
    savedAt: "合成技術規格 · 受控修訂",
    editorState: {
      root: {
        type: "root",
        version: 1,
        direction: null,
        format: "",
        indent: 0,
        children: chapters.flatMap(
          (
            [title, context, oldDecision, oldProcedure, decision, procedure],
            i,
          ) => [
            block(`spec-${i}-heading`, title, true),
            block(`spec-${i}-context`, context),
            block(`spec-${i}-decision`, expanded ? decision : oldDecision),
            block(`spec-${i}-procedure`, expanded ? procedure : oldProcedure),
          ],
        ),
      },
    },
  };
}
function native(snapshot: Snapshot): Snapshot {
  const nodes: Record<string, string> = {};
  const walk = (node: SavedNode, path: string): SavedNode => {
    const { blockId, ...saved } = node;
    if (blockId) nodes[path] = blockId;
    return {
      ...saved,
      ...(node.children
        ? {
            children: node.children.map((child, i) =>
              walk(child, `${path}/children/${i}`),
            ),
          }
        : {}),
    };
  };
  return {
    ...snapshot,
    editorState: { root: walk(snapshot.editorState.root, "/root") },
    identity: { version: 1, namespace: "publication-spec-exercise", nodes },
  };
}
